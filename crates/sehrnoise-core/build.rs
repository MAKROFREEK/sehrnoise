//! Turns `assets/presets.toml` into the preset table the plugin and the
//! standalone app share.
//!
//! The TOML file is the tuning surface: presets can be retuned without touching
//! any Rust code.

use std::fmt::Write as _;
use std::path::PathBuf;

use serde::Deserialize;

/// A preset as it appears in the TOML file.
#[derive(Deserialize)]
struct PresetFile {
    name: String,
    bands_db: Vec<f32>,
    #[serde(default)]
    seed: u64,
    #[serde(default)]
    warp: Option<String>,
    #[serde(default)]
    width: Option<String>,
    #[serde(default)]
    randomize: bool,
    #[serde(default)]
    trim_db: f32,
}

#[derive(Deserialize)]
struct PresetsFile {
    preset: Vec<PresetFile>,
}

/// The path of the preset file in the repository, relative to the crate root.
///
/// This is the tuning surface: one file, edited in place.
const PRESETS_PATH_IN_REPO: &str = "../../assets/presets.toml";

/// The path of the preset file inside the crate.
///
/// A published crate cannot read a file from outside itself, so the crate
/// carries a copy. In the repository the copy is only a fallback: the file
/// in `assets/` wins, and a test makes sure the two never drift apart.
const PRESETS_PATH_IN_CRATE: &str = "presets.toml";

/// Where the preset file is.
///
/// The repository's copy comes first, because that is the one the author
/// edits; a published crate only has its own copy.
fn preset_path() -> PathBuf {
    let in_repo = PathBuf::from(PRESETS_PATH_IN_REPO);
    if in_repo.exists() {
        return in_repo;
    }
    let in_crate = PathBuf::from(PRESETS_PATH_IN_CRATE);
    if in_crate.exists() {
        return in_crate;
    }
    panic!(
        "cannot find the preset file: neither {PRESETS_PATH_IN_REPO} nor \
         {PRESETS_PATH_IN_CRATE} exists"
    );
}

fn main() {
    let path = preset_path();
    println!("cargo:rerun-if-changed={}", path.display());
    println!("cargo:rerun-if-changed={PRESETS_PATH_IN_REPO}");
    println!("cargo:rerun-if-changed={PRESETS_PATH_IN_CRATE}");
    println!("cargo:rerun-if-changed=build.rs");

    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
    let parsed: PresetsFile = toml::from_str(&text)
        .unwrap_or_else(|e| panic!("cannot parse {}: {e}", path.display()));

    let mut out = String::new();
    out.push_str("// @generated by build.rs from assets/presets.toml — do not edit.\n\n");
    out.push_str("pub static PRESETS: &[Preset] = &[\n");

    for preset in &parsed.preset {
        assert_eq!(
            preset.bands_db.len(),
            8,
            "preset '{}' must have exactly eight band gains",
            preset.name
        );

        let bands = preset
            .bands_db
            .iter()
            .map(|v| format!("{v:?}"))
            .collect::<Vec<_>>()
            .join(", ");

        let warp = warp_variant(preset.warp.as_deref());
        let width = width_variant(preset.width.as_deref());

        let _ = writeln!(
            out,
            "    Preset {{\n        name: {:?},\n        bands_db: [{bands}],\n        seed: {},\n        warp: {warp},\n        width: {width},\n        randomize: {},\n        output_trim_db: {:?},\n    }},",
            preset.name,
            preset.seed,
            preset.randomize,
            preset.trim_db,
        );
    }

    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("presets_generated.rs");
    std::fs::write(dest, out).expect("cannot write the generated preset table");
}

fn warp_variant(value: Option<&str>) -> String {
    match value {
        Some(v) => format!("Warp::{v}"),
        None => "Warp::Reset".to_string(),
    }
}

fn width_variant(value: Option<&str>) -> String {
    match value {
        Some("Mono") => "Width::Mono".to_string(),
        Some("Wide") => "Width::Wide".to_string(),
        Some("Normal") => "Width::Normal".to_string(),
        Some(other) => panic!("unknown width: {other}"),
        None => "Width::Normal".to_string(),
    }
}
